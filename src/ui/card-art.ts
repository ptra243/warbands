/* scene helpers: frame is 100 x 100 */
const hd = (cx: number, cy: number, k: number, rot: number, s: string) =>
  `<g transform="translate(${cx},${cy}) rotate(${rot}) scale(${k}) translate(-50,-48)">${s}</g>`; // place the kit's head anywhere, at any size and tilt
const E = (cx: number, cy: number, rx: number, ry: number, fill: string, o?: number | null, extra?: string) =>
  `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}"${o != null ? ` opacity="${o}"` : ''}${extra || ''}/>`;
const PA = (d: string, fill: string, o?: number) =>
  `<path d="${d}" fill="${fill}"${o != null ? ` opacity="${o}"` : ''}/>`;
const sbg = (dark: string, light: string, motif?: string) =>
  P('0,0 100,0 100,100 0,100', dark) + P('0,0 74,0 0,70', light) + (motif || '');
const bolt = (pts: string, c: string, w: number) =>
  L(pts, c, w * 4.5, 0.16) + L(pts, c, w * 2.2, 0.5) + L(pts, c, w, 1) + L(pts, '#ffffff', w * 0.4, 0.95);
